"""Committed Discord avatars for the real test users.

Populate applies tests/data/discord_avatars.py with no network access;
`refresh_test_avatars` rewrites that file from the Discord API.
"""

import re
import time
from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import Final

import requests
from django.conf import settings

from app.models import CustomUser
from tests.data import users as users_data
from tests.data.discord_avatars import DISCORD_AVATARS
from tests.data.models import TestUser

AVATARS_FILE: Final[Path] = (
    Path(__file__).resolve().parent.parent / "data" / "discord_avatars.py"
)
# Synthetic test ids are padded with zeros (100000000000000004, 880000000000000001).
_SYNTHETIC_ID: Final[re.Pattern[str]] = re.compile(r"0{6,}")
_MAX_ATTEMPTS: Final[int] = 5


def apply_committed_avatars(users: Iterable[CustomUser]) -> int:
    """Set each user's committed avatar hash; returns how many changed."""
    updated = 0
    for user in users:
        avatar = DISCORD_AVATARS.get(user.discordId or "")
        if avatar and user.avatar != avatar:
            user.avatar = avatar
            updated += 1
    return updated


def populate_committed_avatars(force: bool = False) -> None:
    """Apply committed avatars to every user whose discord_id has one."""
    users = CustomUser.objects.filter(discordId__in=list(DISCORD_AVATARS))
    print(f"Applied {apply_committed_avatars(users)} committed Discord avatars")


def _iter_test_users(value: object) -> Iterator[TestUser]:
    if isinstance(value, TestUser):
        yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from _iter_test_users(item)
    elif isinstance(value, list | tuple):
        for item in value:
            yield from _iter_test_users(item)


def real_test_discord_ids() -> list[str]:
    """Discord ids of the TestUsers in tests/data/users.py that are real accounts."""
    ids = {
        user.discord_id
        for name in dir(users_data)
        if name.isupper()
        for user in _iter_test_users(getattr(users_data, name))
        if user.discord_id and not _SYNTHETIC_ID.search(user.discord_id)
    }
    return sorted(ids, key=int)


class AvatarFetchError(Exception):
    pass


def fetch_avatar_hash(
    session: requests.Session, discord_id: str, token: str
) -> str | None:
    """Current avatar hash for a Discord user (None: no custom avatar)."""
    url = f"{settings.DISCORD_API_BASE_URL}/users/{discord_id}"
    for _ in range(_MAX_ATTEMPTS):
        resp = session.get(url, headers={"Authorization": f"Bot {token}"}, timeout=10)
        if resp.status_code == 429:
            time.sleep(float(resp.json().get("retry_after", 1)))
            continue
        if resp.headers.get("X-RateLimit-Remaining") == "0":
            time.sleep(float(resp.headers.get("X-RateLimit-Reset-After", 1)))
        if resp.status_code == 404:
            return None
        if resp.status_code != 200:
            raise AvatarFetchError(f"{discord_id}: HTTP {resp.status_code}")
        avatar: str | None = resp.json().get("avatar")
        return avatar
    raise AvatarFetchError(f"{discord_id}: still rate limited")


def render_avatars_module(avatars: dict[str, str]) -> str:
    lines = [
        f'    "{discord_id}": "{avatars[discord_id]}",\n'
        for discord_id in sorted(avatars, key=int)
    ]
    body = "{\n" + "".join(lines) + "}" if lines else "{}"
    return (
        '"""Discord avatar hashes for the real test users, keyed by discord_id.\n'
        "\n"
        "Generated by `just db::avatars::refresh`; do not edit by hand.\n"
        '"""\n'
        "\n"
        f"DISCORD_AVATARS: dict[str, str] = {body}\n"
    )


def refresh_committed_avatars(
    token: str,
) -> tuple[dict[str, str], list[str], list[str]]:
    """Fetch every real test user's avatar and rewrite the committed module.

    Returns (avatars, ids without an avatar, ids that failed). A failed fetch
    keeps the previously committed hash.
    """
    avatars: dict[str, str] = {}
    missing: list[str] = []
    failed: list[str] = []
    with requests.Session() as session:
        for discord_id in real_test_discord_ids():
            try:
                avatar = fetch_avatar_hash(session, discord_id, token)
            except (AvatarFetchError, requests.RequestException) as e:
                print(f"  {e}")
                failed.append(discord_id)
                if discord_id in DISCORD_AVATARS:
                    avatars[discord_id] = DISCORD_AVATARS[discord_id]
                continue
            if avatar:
                avatars[discord_id] = avatar
            else:
                missing.append(discord_id)
    AVATARS_FILE.write_text(render_avatars_module(avatars))
    return avatars, missing, failed
