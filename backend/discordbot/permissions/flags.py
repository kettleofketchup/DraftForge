BIT: dict[PermissionFlag, int] = {
    flag: 1 << position
    for flag, position in zip(PermissionFlag, (*range(47), 49, 50), strict=True)
}
ALL_KNOWN: int = sum(BIT.values())

# discord.py Permissions.all_channel() excludes these guild-only flags.
_GUILD_SCOPED: tuple[PermissionFlag, ...] = (
    PermissionFlag.KICK_MEMBERS,
    PermissionFlag.BAN_MEMBERS,
    PermissionFlag.ADMINISTRATOR,
    PermissionFlag.MANAGE_GUILD,
    PermissionFlag.VIEW_AUDIT_LOG,
    PermissionFlag.VIEW_GUILD_INSIGHTS,
    PermissionFlag.CHANGE_NICKNAME,
    PermissionFlag.MANAGE_NICKNAMES,
    PermissionFlag.MANAGE_GUILD_EXPRESSIONS,
    PermissionFlag.MANAGE_EVENTS,
    PermissionFlag.MODERATE_MEMBERS,
    PermissionFlag.VIEW_CREATOR_MONETIZATION_ANALYTICS,
    PermissionFlag.CREATE_GUILD_EXPRESSIONS,
    PermissionFlag.CREATE_EVENTS,
)
CHANNEL_SCOPED_MASK: int = ALL_KNOWN & ~sum(BIT[flag] for flag in _GUILD_SCOPED)


def labels(bits: int) -> list[str]:
    return [flag.value for flag, bit in BIT.items() if bits & bit]
