def test_registry_dir_absolute_from_main_checkout_layout(tmp_path: Path) -> None:
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    d = registry_dir(tmp_path, REAL_HOST)
    assert d.is_absolute() and d == (tmp_path / ".git" / "df-slots").resolve()


def test_registry_dir_uses_host_common_dir(tmp_path: Path) -> None:
    h = FakeHost(tmp_path / "common")
    assert registry_dir(tmp_path, h) == tmp_path / "common" / "df-slots"
