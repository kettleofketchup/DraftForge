def test_slot_env_from_kv_rejects_missing_keys() -> None:
    with pytest.raises(SlotError):
        slot_env_from_kv({"DF_SLOT": "1"})


def test_parse_kv_ignores_comments_and_blanks() -> None:
    assert parse_kv("# c\n\nA=1\nB=x=y\n") == {"A": "1", "B": "x=y"}


def test_atomic_write_skips_identical(tmp_path: Path) -> None:
    p = tmp_path / "f"
    assert atomic_write(p, "a\n", skip_if_same=True) is True
    ino = p.stat().st_ino
    assert atomic_write(p, "a\n", skip_if_same=True) is False
    assert p.stat().st_ino == ino
    assert atomic_write(p, "b\n", skip_if_same=True) is True
    assert p.stat().st_ino != ino
    assert [x.name for x in tmp_path.iterdir()] == ["f"]


def test_atomic_write_always_writes_without_skip(tmp_path: Path) -> None:
    p = tmp_path / "f"
    atomic_write(p, "a\n", skip_if_same=False)
    assert atomic_write(p, "a\n", skip_if_same=False) is True


def test_ci_mode_only_github_actions(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delenv("GITHUB_ACTIONS", raising=False)
    monkeypatch.setenv("CI", "true")
    assert is_ci() is False
    monkeypatch.setenv("GITHUB_ACTIONS", "true")
    assert is_ci() is True


