class SlotError(Exception):
    pass


class NoSlotFile(SlotError):
    pass


@dataclass(frozen=True)
class SlotEnv:
    slot: int
    suffix: str
    project: str
    https_port: int
    http_port: int | None
    base_url: str
    background: bool
    worktree: Path
    token: str
    registry: Path | None


@dataclass(frozen=True)
class ContainerOwner:
    name: str
    running: bool
    project: str
    service: str
    working_dir: Path | None
    config_files: tuple[str, ...]
    oneoff: bool


@dataclass(frozen=True)
class Host:
    port_busy: Callable[[int], bool]
    containers: Callable[[str], list[ContainerOwner]]
    service_containers: Callable[[str], list[ContainerOwner]]
    all_df_containers: Callable[[], list[ContainerOwner]]
    common_dir: Callable[[Path], Path]
    live_worktrees: Callable[[Path], set[Path]]
    run: Callable[[list[str], Mapping[str, str], bool], tuple[int, str]]
    clock: Callable[[], float]
    new_token: Callable[[], str]


def is_ci() -> bool:
    return os.environ.get("GITHUB_ACTIONS") == "true"


def slot_env_for(
    n: int, worktree: Path, token: str, registry: Path | None, background: bool | None = None
) -> SlotEnv:
    if not 0 <= n < SLOT_COUNT:
        raise SlotError(f"slot {n} out of range [0, {SLOT_COUNT - 1}]")
    https_port = 443 if n == 0 else 10443 + n * 1000
    return SlotEnv(
        slot=n,
        suffix="" if n == 0 else f"-s{n}",
        project="df" if n == 0 else f"df-s{n}",
        https_port=https_port,
        http_port=80 if n == 0 else None,
        base_url="https://localhost" if n == 0 else f"https://localhost:{https_port}",
        background=(n == 0) if background is None else background,
        worktree=worktree.resolve(),
        token=token,
        registry=registry,
    )


def ci_slot(root: Path) -> SlotEnv:
    return slot_env_for(0, root, "ci", None)


def render_slot_file(env: SlotEnv) -> str:
    values = {
        "DF_SLOT": str(env.slot),
        "DF_SUFFIX": env.suffix,
        "COMPOSE_PROJECT_NAME": env.project,
        "DF_HTTPS_PORT": str(env.https_port),
        "DF_HTTP_PORT": "" if env.http_port is None else str(env.http_port),
        "DF_BASE_URL": env.base_url,
        "DF_BACKGROUND": "1" if env.background else "0",
        "DF_WORKTREE": str(env.worktree),
        "DF_SLOT_TOKEN": env.token,
        "DF_REGISTRY": "" if env.registry is None else str(env.registry),
    }
    return "\n".join([SLOT_FILE_HEADER, *(f"{k}={values[k]}" for k in SLOT_KEYS)]) + "\n"


def parse_kv(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        out[key.strip()] = value
    return out


def slot_env_from_kv(kv: Mapping[str, str]) -> SlotEnv:
    missing = [k for k in SLOT_KEYS if k not in kv]
    if missing:
        raise SlotError(f"slot file is missing keys: {', '.join(missing)}")
    try:
        slot = int(kv["DF_SLOT"])
        https_port = int(kv["DF_HTTPS_PORT"])
        http_port = int(kv["DF_HTTP_PORT"]) if kv["DF_HTTP_PORT"] else None
    except ValueError as exc:
        raise SlotError(f"slot file has a malformed number: {exc}") from exc
    if not 0 <= slot < SLOT_COUNT:
        raise SlotError(f"slot file names slot {slot}, out of range [0, {SLOT_COUNT - 1}]")
    return SlotEnv(
        slot=slot,
        suffix=kv["DF_SUFFIX"],
        project=kv["COMPOSE_PROJECT_NAME"],
        https_port=https_port,
        http_port=http_port,
        base_url=kv["DF_BASE_URL"],
        background=kv["DF_BACKGROUND"] == "1",
        worktree=Path(kv["DF_WORKTREE"]),
        token=kv["DF_SLOT_TOKEN"],
        registry=Path(kv["DF_REGISTRY"]) if kv["DF_REGISTRY"] else None,
    )


def atomic_write(path: Path, text: str, *, skip_if_same: bool) -> bool:
    if skip_if_same:
        try:
            if path.read_text() == text:
                return False
        except FileNotFoundError:
            pass
    tmp = tempfile.NamedTemporaryFile("w", dir=path.parent, prefix=f".{path.name}.", delete=False)
    try:
        with tmp:
            tmp.write(text)
            tmp.flush()
            os.fsync(tmp.fileno())
        os.chmod(tmp.name, 0o644)
        os.replace(tmp.name, path)
    except BaseException:
        Path(tmp.name).unlink(missing_ok=True)
        raise
    return True


def registry_dir(root: Path, host: Host) -> Path:
    return host.common_dir(root) / "df-slots"


def _label(value: str) -> str:
    return "" if value == "<no value>" else value


def parse_ps_output(text: str) -> list[ContainerOwner]:
    owners: list[ContainerOwner] = []
    for line in text.splitlines():
        if not line.strip():
            continue
        fields = [_label(f) for f in line.split("\t")]
        fields += [""] * (7 - len(fields))
        name, state, project, service, wd, config_files, oneoff = fields[:7]
        working_dir: Path | None = None
        if wd:
            p = Path(wd)
            working_dir = p.resolve() if p.exists() else p
        owners.append(
            ContainerOwner(
                name=name,
                running=state.lower() == "running",
                project=project,
                service=service,
                working_dir=working_dir,
                config_files=tuple(f for f in config_files.split(",") if f),
                oneoff=oneoff.lower() == "true",
            )
        )
    return owners


def port_busy(port: int) -> bool:
    if shutil.which("ss"):
        r = subprocess.run(
            ["ss", "-ltnH", f"sport = :{port}"], capture_output=True, text=True, check=False
        )
        if r.returncode == 0:
            return bool(r.stdout.strip())
    with socket.socket() as s:
        s.settimeout(0.5)
        return s.connect_ex(("127.0.0.1", port)) == 0


def _docker_ps(args: list[str]) -> list[ContainerOwner]:
    r = subprocess.run(
        ["docker", "ps", *args, "--format", PS_FORMAT], capture_output=True, text=True, check=False
    )
    if r.returncode != 0:
        raise SlotError(f"docker ps failed ({r.returncode}): {r.stderr.strip()}")
    return parse_ps_output(r.stdout)


def _containers(project: str) -> list[ContainerOwner]:
    return _docker_ps(["-a", "--filter", f"label=com.docker.compose.project={project}"])


def _service_containers(service: str) -> list[ContainerOwner]:
    return _docker_ps(["--filter", f"label=com.docker.compose.service={service}"])


def _all_df_containers() -> list[ContainerOwner]:
    return [o for o in _docker_ps(["-a"]) if DF_PROJECT_RE.match(o.project)]


def _git(root: Path, *args: str) -> str:
    r = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, check=False)
    if r.returncode != 0:
        raise SlotError(f"git {' '.join(args)} failed in {root}: {r.stderr.strip()}")
    return r.stdout


def _common_dir(root: Path) -> Path:
    return Path(_git(root, "rev-parse", "--path-format=absolute", "--git-common-dir").strip()).resolve()


def _live_worktrees(root: Path) -> set[Path]:
    out = _git(root, "worktree", "list", "--porcelain")
    return {Path(line[len("worktree ") :]).resolve() for line in out.splitlines() if line.startswith("worktree ")}


def _run(argv: list[str], env: Mapping[str, str], capture: bool) -> tuple[int, str]:
    r = subprocess.run(
        argv,
        env={**os.environ, **env},
        stdout=subprocess.PIPE if capture else None,
        text=True,
        check=False,
    )
    return r.returncode, r.stdout if capture else ""


