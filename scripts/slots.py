@dataclass(frozen=True)
class Reservation:
    slot: int
    owner: Path
    token: str
    last_used: int


def _project(n: int) -> str:
    return "df" if n == 0 else f"df-s{n}"


def _ports(n: int) -> list[int]:
    e = slot_env_for(n, Path("/"), "", None)
    return [e.https_port] if e.http_port is None else [e.http_port, e.https_port]


@contextmanager
def registry_lock(registry: Path) -> Iterator[None]:
    registry.mkdir(parents=True, exist_ok=True)
    fd = os.open(registry / ".lock", os.O_RDWR | os.O_CREAT, 0o644)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX)
        yield
    finally:
        os.close(fd)


def _read_reservation(registry: Path, n: int) -> Reservation | None:
    try:
        kv = parse_kv((registry / f"slot-{n}").read_text())
    except FileNotFoundError:
        return None
    try:
        last_used = int(kv.get("last_used", "0"))
    except ValueError:
        last_used = 0
    return Reservation(
        slot=n,
        owner=Path(kv.get("owner", "")),
        token=kv.get("token", ""),
        last_used=last_used,
    )


def _write_reservation(
    registry: Path, n: int, owner_path: Path, token: str, last_used: int
) -> None:
    text = f"owner={owner_path}\ntoken={token}\nlast_used={last_used}\n"
    atomic_write(registry / f"slot-{n}", text, skip_if_same=False)


def _read_slot_kv(root: Path) -> dict[str, str] | None:
    try:
        return parse_kv((root / SLOT_FILE_REL).read_text())
    except FileNotFoundError:
        return None


def _check_worktree(kv: Mapping[str, str], root: Path) -> None:
    written_for = kv.get("DF_WORKTREE", "")
    if Path(written_for) != root:
        raise SlotError(
            f"`.env.slot` was written for {written_for}, not {root}; "
            f"delete {root / SLOT_FILE_REL} and run `just test::slot`"
        )


def _is_stale(res: Reservation) -> bool:
    if not res.owner.exists():
        return True
    kv = _read_slot_kv(res.owner)
    if kv is None:
        return False
    return kv.get("DF_SLOT") != str(res.slot) or kv.get("DF_SLOT_TOKEN") != res.token


def _own(owners: list[ContainerOwner], root: Path) -> list[ContainerOwner]:
    return [o for o in owners if not o.oneoff and o.working_dir == root]


def _foreign(owners: list[ContainerOwner], root: Path) -> list[ContainerOwner]:
    return [o for o in owners if not o.oneoff and o.working_dir != root]


def _check_legacy_dev(df_owners: list[ContainerOwner]) -> None:
    for o in df_owners:
        dev_files = [f for f in o.config_files if _is_dev_file(f)]
        if not dev_files:
            continue
        raise SlotError(
            f"project df is a legacy dev stack from {o.working_dir} ({', '.join(dev_files)}); "
            f"stop it before using test slot 0: {_legacy_dev_cleanup(o)}"
        )


def _check_containers(n: int, root: Path, owners: list[ContainerOwner]) -> None:
    foreign = _foreign(owners, root)
    if not foreign:
        return
    o = foreign[0]
    if n == 0:
        raise SlotError(
            f"`df` was taken over by {o.working_dir} (config files: {', '.join(o.config_files)}); "
            f"that worktree probably runs code without test slots: merge main into it, "
            f"then run `just test::slot` there"
        )
    raise SlotError(
        f"project {_project(n)} has containers from {o.working_dir}, not {root}"
    )


def _check_reservation(n: int, root: Path, token: str, res: Reservation | None) -> None:
    if res is None:
        raise SlotError(f"no reservation for slot {n}; run `just test::slot`")
    if res.owner != root or res.token != token:
        raise SlotError(
            f"slot {n} now belongs to {res.owner}; run `just test::slot` to get a new slot"
        )


def _requested_slot(requested: int | None) -> int | None:
    if requested is None:
        raw = os.environ.get("DF_SLOT", "")
        if not raw:
            return None
        try:
            requested = int(raw)
        except ValueError as exc:
            raise SlotError(f"DF_SLOT={raw!r} is not a slot number") from exc
    if not 0 <= requested < SLOT_COUNT:
        raise SlotError(
            f"requested slot {requested} out of range [0, {SLOT_COUNT - 1}]"
        )
    return requested


class _Allocator:
    def __init__(
        self, root: Path, host: Host, registry: Path, requested: int | None
    ) -> None:
        self.root = root
        self.host = host
        self.registry = registry
        self.requested = requested
        self.candidates: list[int] = (
            list(range(SLOT_COUNT)) if requested is None else [requested]
        )
        self._owners: dict[int, list[ContainerOwner]] = {}

    def owners(self, n: int) -> list[ContainerOwner]:
        if n not in self._owners:
            self._owners[n] = self.host.containers(_project(n))
        return self._owners[n]

    def _readopt(self, res: Reservation) -> tuple[int, str]:
        self._check_request(res.slot)
        _check_containers(res.slot, self.root, self.owners(res.slot))
        return res.slot, res.token

    def _check_request(self, n: int) -> None:
        if self.requested is not None and self.requested != n:
            raise SlotError(
                f"this worktree already holds slot {n} but DF_SLOT asks for {self.requested}; "
                f"run `just test::slot-release` first"
            )

    def existing(
        self, prev: dict[str, str] | None
    ) -> tuple[tuple[int, str] | None, int | None]:
        if prev is None:
            for n in range(SLOT_COUNT):
                res = _read_reservation(self.registry, n)
                if res is not None and res.owner == self.root:
                    return self._readopt(res), None
            return None, None
        n = slot_env_from_kv(prev).slot
        res = _read_reservation(self.registry, n)
        if res is not None and res.owner == self.root:
            return self._readopt(res), None
        if res is not None and _own(self.owners(n), self.root):
            raise SlotError(
                f"slot {n} now belongs to {res.owner}, but this worktree still has containers "
                f"in {_project(n)}; sort it out with that worktree's owner"
            )
        return None, n

    def adopt(self) -> int | None:
        for n in self.candidates:
            if not _own(self.owners(n), self.root):
                continue
            if n == 0:
                _check_legacy_dev(self.owners(0))
            _check_containers(n, self.root, self.owners(n))
            res = _read_reservation(self.registry, n)
            if res is not None and res.owner != self.root and not _is_stale(res):
                continue
            return n
        return None

    def fresh(self) -> int | None:
        for n in self.candidates:
            if n == 0:
                _check_legacy_dev(self.owners(0))
            res = _read_reservation(self.registry, n)
            if res is not None and res.owner != self.root:
                if not _is_stale(res):
                    continue
                if self.owners(n):
                    p = _project(n)
                    print(
                        f"slot {n}: reservation for {res.owner} is stale but {p} still has containers "
                        f"(orphan stack); check it, then run `just test::slot-reap {p}`",
                        file=sys.stderr,
                    )
                    continue
            if _foreign(self.owners(n), self.root):
                continue
            if any(self.host.port_busy(p) for p in _ports(n)):
                continue
            return n
        return None

    def idle_reclaim(self) -> int | None:
        now = self.host.clock()
        idle: list[tuple[int, int]] = []
        for n in self.candidates:
            if n == 0:
                continue
            res = _read_reservation(self.registry, n)
            if (
                res is None
                or res.owner == self.root
                or now - res.last_used <= LEASE_TTL_S
            ):
                continue
            if self.owners(n):
                continue
            idle.append((res.last_used, n))
        for _, n in sorted(idle):
            if not any(self.host.port_busy(p) for p in _ports(n)):
                return n
        return None

    def exhausted(self) -> SlotError:
        now = self.host.clock()
        head = (
            f"slot {self.requested} is not free"
            if self.requested is not None
            else "no free test slot"
        )
        lines = [f"{head}:"]
        for n in self.candidates:
            res = _read_reservation(self.registry, n)
            who = str(res.owner) if res else "-"
            age = f"{(now - res.last_used) / 86_400:.1f}d" if res else "-"
            lines.append(
                f"  slot {n}: owner={who} containers={len(self.owners(n))} lease_age={age}"
            )
        lines.append(
            "free one with `just test::slot-release --slot N` (needs zero containers) "
            "or move one here with `just test::slot-claim N`"
        )
        return SlotError("\n".join(lines))


def ensure_slot(
    root: Path | None = None, host: Host | None = None, *, requested: int | None = None
) -> SlotEnv:
    root = (root or MODULE_ROOT).resolve()
    if is_ci():
        return ci_slot(root)
    host = host or REAL_HOST
    requested = _requested_slot(requested)
    registry = registry_dir(root, host)
    notice: str | None = None
    with registry_lock(registry):
        prev = _read_slot_kv(root)
        if prev is not None:
            _check_worktree(prev, root)
        alloc = _Allocator(root, host, registry, requested)
        kept, lost = alloc.existing(prev)
        if kept is not None:
            n, token = kept
        else:
            if _reap_stale_locked(root, host, registry):
                alloc = _Allocator(root, host, registry, requested)
            found = alloc.adopt()
            if found is None:
                found = alloc.fresh()
            if found is None and requested is None:
                found = alloc.idle_reclaim()
            if found is None:
                raise alloc.exhausted()
            n, token = found, host.new_token()
            if lost is not None and lost != n:
                notice = f"slot {lost} was reclaimed while idle; now slot {n}"
        background: bool | None = None
        if (
            prev is not None
            and prev.get("DF_SLOT") == str(n)
            and "DF_BACKGROUND" in prev
        ):
            background = prev["DF_BACKGROUND"] == "1"
        env = slot_env_for(n, root, token, registry, background)
        _write_reservation(registry, n, root, token, int(host.clock()))
        atomic_write(root / SLOT_FILE_REL, render_slot_file(env), skip_if_same=True)
    if notice:
        print(notice, file=sys.stderr)
    return env


def read_slot(root: Path | None = None, host: Host | None = None) -> SlotEnv:
    root = (root or MODULE_ROOT).resolve()
    if is_ci():
        return ci_slot(root)
    host = host or REAL_HOST
    kv = _read_slot_kv(root)
    if kv is None:
        raise NoSlotFile(
            f"no slot file at {root / SLOT_FILE_REL}; run `just test::slot`"
        )
    _check_worktree(kv, root)
    env = slot_env_from_kv(kv)
    registry = registry_dir(root, host)
    _check_reservation(env.slot, root, env.token, _read_reservation(registry, env.slot))
    _check_containers(env.slot, root, host.containers(env.project))
    return replace(env, registry=registry)


def lease_and_recheck(env: SlotEnv, host: Host | None = None) -> None:
    if is_ci():
        return
    host = host or REAL_HOST
    registry = env.registry or registry_dir(env.worktree, host)
    with registry_lock(registry):
        res = _read_reservation(registry, env.slot)
        if res is None or res.owner != env.worktree or res.token != env.token:
            who = res.owner if res is not None else "nobody (reservation removed)"
            raise SlotError(
                f"slot {env.slot} was taken by {who} since this command started; run `just test::slot`"
            )
        _write_reservation(
            registry, env.slot, env.worktree, env.token, int(host.clock())
        )


REAP_NAME_RE: Final = re.compile(r"^df(-dev|-s[0-9]|-run-[0-9a-f]{8})?$")
TRANSITION_WARNING: Final = (
    "worktrees on branches without this feature can still kill or hijack slot stacks; "
    "merge main into them first."
)
BACKGROUND_SERVICES: Final = ("discord-bot", "celery-beat")


def _refuse_in_ci(what: str) -> None:
    if is_ci():
        raise SlotError(f"{what} is not available in CI mode (GITHUB_ACTIONS=true)")


def _slot_of_project(project: str) -> int | None:
    if project == "df":
        return 0
    m = re.fullmatch(r"df-s([0-9])", project)
    return int(m.group(1)) if m else None


def _is_ours(res: Reservation | None, root: Path, token: str | None) -> bool:
    return (
        res is not None and res.owner == root and (token is None or res.token == token)
    )


def _held(
    registry: Path, root: Path, kv: Mapping[str, str] | None
) -> list[tuple[int, str | None]]:
    held: dict[int, str | None] = {}
    for n in range(SLOT_COUNT):
        res = _read_reservation(registry, n)
        if res is not None and res.owner == root:
            held[n] = None
    if kv is not None:
        env = slot_env_from_kv(kv)
        held[env.slot] = env.token
    return sorted(held.items())


def _check_releasable(
    n: int, root: Path, host: Host, res: Reservation | None, token: str | None
) -> None:
    owners = host.containers(_project(n))
    if res is None or _is_ours(res, root, token):
        blocking = owners
    else:
        blocking = _own(owners, root)
    if blocking:
        raise SlotError(
            f"slot {n} still has {len(blocking)} container(s) in {_project(n)}; "
            f"run `just test::down` first"
        )


def _check_target_free_of_containers(n: int, host: Host) -> None:
    owners = host.containers(_project(n))
    if owners:
        raise SlotError(
            f"slot {n} has {len(owners)} container(s) in {_project(n)}; "
            f"its owner must run `just test::down` first"
        )


def _check_target_free(n: int, host: Host) -> None:
    _check_target_free_of_containers(n, host)
    for p in _ports(n):
        if host.port_busy(p):
            raise SlotError(f"port {p} is busy; slot {n} cannot start here")


def _drop_reservation(registry: Path, n: int, root: Path, token: str | None) -> None:
    res = _read_reservation(registry, n)
    if res is None:
        print(f"slot {n} reservation was already gone", file=sys.stderr)
    elif _is_ours(res, root, token):
        (registry / f"slot-{n}").unlink(missing_ok=True)
    else:
        print(
            f"slot {n} reservation now belongs to {res.owner}; left it alone",
            file=sys.stderr,
        )


def release_slot(
    root: Path | None = None, host: Host | None = None, *, slot: int | None = None
) -> None:
    root = (root or MODULE_ROOT).resolve()
    _refuse_in_ci("slot release")
    host = host or REAL_HOST
    registry = registry_dir(root, host)
    with registry_lock(registry):
        kv = _read_slot_kv(root)
        if kv is not None:
            _check_worktree(kv, root)
        own_slot = slot_env_from_kv(kv).slot if kv is not None else None
        if slot is not None and slot != own_slot:
            if not 0 <= slot < SLOT_COUNT:
                raise SlotError(f"slot {slot} out of range [0, {SLOT_COUNT - 1}]")
            _check_target_free_of_containers(slot, host)
            if _read_reservation(registry, slot) is None:
                print(f"slot {slot} has no reservation", file=sys.stderr)
            (registry / f"slot-{slot}").unlink(missing_ok=True)
            return
        held = _held(registry, root, kv)
        if not held:
            print("this worktree holds no slot", file=sys.stderr)
            return
        for n, token in held:
            _check_releasable(n, root, host, _read_reservation(registry, n), token)
        for n, token in held:
            _drop_reservation(registry, n, root, token)
        (root / SLOT_FILE_REL).unlink(missing_ok=True)


def claim_slot(n: int, root: Path | None = None, host: Host | None = None) -> SlotEnv:
    root = (root or MODULE_ROOT).resolve()
    _refuse_in_ci("slot claim")
    host = host or REAL_HOST
    if not 0 <= n < SLOT_COUNT:
        raise SlotError(f"slot {n} out of range [0, {SLOT_COUNT - 1}]")
    registry = registry_dir(root, host)
    with registry_lock(registry):
        kv = _read_slot_kv(root)
        if kv is not None:
            _check_worktree(kv, root)
            current = slot_env_from_kv(kv)
            if current.slot == n and _is_ours(
                _read_reservation(registry, n), root, current.token
            ):
                return replace(current, registry=registry)
        held = _held(registry, root, kv)
        for m, token in held:
            _check_releasable(m, root, host, _read_reservation(registry, m), token)
        _check_target_free(n, host)
        for m, token in held:
            _drop_reservation(registry, m, root, token)
        token = host.new_token()
        env = slot_env_for(n, root, token, registry)
        _write_reservation(registry, n, root, token, int(host.clock()))
        atomic_write(root / SLOT_FILE_REL, render_slot_file(env), skip_if_same=False)
    return env


def reap_project(
    project: str, root: Path | None = None, host: Host | None = None
) -> None:
    root = (root or MODULE_ROOT).resolve()
    _refuse_in_ci("slot reap")
    host = host or REAL_HOST
    if not REAP_NAME_RE.match(project):
        raise SlotError(
            f"refusing to reap {project!r}: only df, df-dev, df-s<N> and df-run-<hex> are accepted"
        )
    registry = registry_dir(root, host)
    with registry_lock(registry):
        live = host.live_worktrees(root)
        for o in host.containers(project):
            wd = o.working_dir
            if not o.oneoff and wd is not None and wd in live and wd.exists():
                raise SlotError(
                    f"refusing to reap {project}: container {o.name} belongs to the live "
                    f"worktree {wd}; run `just test::down` there instead"
                )
        argv = ["docker", "compose", "-p", project, "down", "-v", "--remove-orphans"]
        code, _ = host.run(argv, {}, False)
        if code != 0:
            raise SlotError(f"`{' '.join(argv)}` exited {code}")
        n = _slot_of_project(project)
        if n is not None:
            (registry / f"slot-{n}").unlink(missing_ok=True)


STALE_HOURS_DEFAULT: Final = 12.0
TEST_STACK_FILES: Final = frozenset(
    {
        "docker-compose.test.yaml",
        "docker-compose.slot.yaml",
        "docker-compose.slot-offline.yaml",
        "docker-compose.run.yaml",
    }
)


def stale_after_s() -> float:
    raw = os.environ.get("DF_SLOT_STALE_HOURS", "")
    if not raw:
        return STALE_HOURS_DEFAULT * 3600
    try:
        hours = float(raw)
    except ValueError as exc:
        raise SlotError(f"DF_SLOT_STALE_HOURS={raw!r} is not a number") from exc
    if hours <= 0:
        raise SlotError(f"DF_SLOT_STALE_HOURS={raw!r} must be positive")
    return hours * 3600


@dataclass(frozen=True)
class StaleSlot:
    slot: int
    project: str
    owner: Path | None
    containers: int
    last_activity: float
    source: str


def _idle_since(
    project: str,
    res: Reservation | None,
    owners: list[ContainerOwner],
    host: Host,
    cutoff: float,
) -> tuple[float, str] | None:
    signals: list[tuple[float, str]] = []
    if res is not None:
        if res.last_used >= cutoff:
            return None
        signals.append((float(res.last_used), "reservation"))
    if owners:
        t = host.container_activity(project)
        if t is None or t >= cutoff:
            return None
        signals.append((t, "containers"))
    paths = {o.working_dir for o in owners if o.working_dir is not None}
    if res is not None:
        paths.add(res.owner)
    for p in sorted(paths):
        t = host.worktree_activity(p)
        if t is not None:
            if t >= cutoff:
                return None
            signals.append((t, f"worktree {p}"))
    return max(signals, default=None)


def _reap_stale_locked(root: Path, host: Host, registry: Path) -> list[StaleSlot]:
    limit = stale_after_s()
    now = host.clock()
    reaped: list[StaleSlot] = []
    for n in range(SLOT_COUNT):
        project = _project(n)
        res = _read_reservation(registry, n)
        owners = host.containers(project)
        if res is None and not owners:
            continue
        if (res is not None and res.owner == root) or any(
            o.working_dir == root for o in owners
        ):
            continue
        if any(
            Path(f).name not in TEST_STACK_FILES for o in owners for f in o.config_files
        ):
            continue
        try:
            idle = _idle_since(project, res, owners, host, now - limit)
        except SlotError as exc:
            print(f"slot {n}: not reaping, activity unknown: {exc}", file=sys.stderr)
            continue
        if idle is None:
            continue
        if owners:
            argv = [
                "docker",
                "compose",
                "-p",
                project,
                "down",
                "-v",
                "--remove-orphans",
            ]
            code, _ = host.run(argv, {}, False)
            if code != 0:
                print(
                    f"slot {n}: not reaping, `{' '.join(argv)}` exited {code}",
                    file=sys.stderr,
                )
                continue
        (registry / f"slot-{n}").unlink(missing_ok=True)
        stale = StaleSlot(
            slot=n,
            project=project,
            owner=res.owner if res is not None else owners[0].working_dir,
            containers=len(owners),
            last_activity=idle[0],
            source=idle[1],
        )
        removed = (
            f"; {stale.containers} container(s) and volumes removed"
            if stale.containers
            else ""
        )
        print(
            f"auto-reaped slot {n} ({project}), owner {stale.owner}: "
            f"idle {(now - stale.last_activity) / 3600:.1f}h > {limit / 3600:g}h "
            f"(last activity: {stale.source}){removed}",
            file=sys.stderr,
        )
        reaped.append(stale)
    return reaped


def reap_stale(root: Path | None = None, host: Host | None = None) -> list[StaleSlot]:
    root = (root or MODULE_ROOT).resolve()
    _refuse_in_ci("slot reap")
    host = host or REAL_HOST
    registry = registry_dir(root, host)
    with registry_lock(registry):
        return _reap_stale_locked(root, host, registry)


def check_background_free(slot: SlotEnv | None, project: str, host: Host) -> None:
    if (
        os.environ.get("DF_BACKGROUND_PROOF") == "1"
        and slot is not None
        and slot.slot >= 1
    ):
        return
    for service in BACKGROUND_SERVICES:
        for o in host.service_containers(service):
            if o.project != project:
                raise SlotError(
                    f"{service} is already running in project {o.project} ({o.working_dir}); "
                    f"only one stack may run the Discord bot and celery beat at a time"
                )


def set_background(
    on: bool, root: Path | None = None, host: Host | None = None
) -> SlotEnv:
    root = (root or MODULE_ROOT).resolve()
    _refuse_in_ci("slot background")
    host = host or REAL_HOST
    env = read_slot(root, host)
    if on:
        check_background_free(env, env.project, host)
    with registry_lock(env.registry or registry_dir(root, host)):
        new = replace(env, background=on)
        atomic_write(root / SLOT_FILE_REL, render_slot_file(new), skip_if_same=True)
    return new


def _reservation_state(res: Reservation, live: set[Path], now: float) -> str:
    if _is_stale(res) or res.owner not in live:
        return "stale"
    if res.slot != 0 and now - res.last_used > LEASE_TTL_S:
        return "idle"
    return "live"


def status_report(root: Path | None = None, host: Host | None = None) -> str:
    root = (root or MODULE_ROOT).resolve()
    host = host or REAL_HOST
    registry = registry_dir(root, host)
    live = host.live_worktrees(root)
    now = host.clock()
    by_project: dict[str, list[ContainerOwner]] = {}
    for o in host.all_df_containers():
        by_project.setdefault(o.project, []).append(o)
    reservations = {
        n: res
        for n in range(SLOT_COUNT)
        if (res := _read_reservation(registry, n)) is not None
    }
    lines = [f"registry: {registry}"]
    if not reservations:
        lines.append("  (no reservations)")
    for n, res in reservations.items():
        age = (now - res.last_used) / 86_400
        lines.append(
            f"slot {n} {_reservation_state(res, live, now)} owner={res.owner} "
            f"containers={len(by_project.get(_project(n), []))} lease_age={age:.1f}d"
        )
    for project in sorted(by_project):
        owners = by_project[project]
        n = _slot_of_project(project)
        res = reservations.get(n) if n is not None else None
        stack = [o for o in owners if not o.oneoff]
        wds = sorted({str(o.working_dir) for o in owners if o.working_dir is not None})
        files = sorted({f for o in owners for f in o.config_files})
        live_owner = next(
            (
                o.working_dir
                for o in stack
                if o.working_dir is not None
                and o.working_dir in live
                and o.working_dir.exists()
            ),
            None,
        )
        reap = f"check it, then run `just test::slot-reap {project}`"
        if not stack:
            label = f"orphan hint (one-off only); {reap}"
        elif live_owner is not None:
            if res is not None and res.owner == live_owner:
                label = f"slot {n} (owner live: {live_owner})"
            elif res is not None:
                label = f"reserved by {res.owner}, containers from live {live_owner}"
            else:
                label = f"unreserved (owner live: {live_owner})"
        else:
            label = f"orphan (owner gone); {reap}"
        lines.append(f"project {project} containers={len(owners)} {label}")
        lines.append(f"  working_dir: {', '.join(wds) or '-'}")
        lines.append(f"  config_files: {', '.join(files) or '-'}")
    limit = stale_after_s()
    if any(now - r.last_used > limit for r in reservations.values()):
        lines.append(
            f"reservations idle over {limit / 3600:g}h are reaped on the next allocation unless "
            f"their containers or worktree were active since; `just test::slot-reap --stale` now"
        )
    return "\n".join(lines) + "\n"


